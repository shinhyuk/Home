// 지역명 → 코드 변환 (유연한 매칭)
function resolveLawdCode(input) {
  if (!input) return null;
  const trimmed = input.trim();

  // 정확히 일치
  if (LAWD_CODES[trimmed]) {
    return { name: trimmed, code: LAWD_CODES[trimmed] };
  }

  // 별칭 확인
  for (const [alias, fullName] of Object.entries(ALIASES)) {
    if (trimmed.includes(alias)) {
      return { name: fullName, code: LAWD_CODES[fullName] };
    }
  }

  // 부분 일치 (예: "강남구" → "서울 강남구")
  const normalized = trimmed.replace(/\s+/g, '');
  for (const [name, code] of Object.entries(LAWD_CODES)) {
    const nameNorm = name.replace(/\s+/g, '');
    if (nameNorm.includes(normalized) || normalized.includes(nameNorm)) {
      return { name, code };
    }
  }

  // 구 단위 부분 일치
  for (const [name, code] of Object.entries(LAWD_CODES)) {
    const parts = name.split(' ');
    const gu = parts[parts.length - 1];
    if (trimmed.includes(gu) && gu.length >= 2) {
      return { name, code };
    }
  }

  return null;
}

function listRegions() {
  return Object.keys(LAWD_CODES);
}

module.exports = { LAWD_CODES, ALIASES, resolveLawdCode, listRegions };
